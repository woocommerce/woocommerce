#!/usr/bin/env node
/**
 * Generates .github/coderabbit/wpds-tokens.md from the token data exported by
 * the installed @wordpress/theme package, for use as a CodeRabbit guideline.
 *
 * Usage: node bin/generate-wpds-tokens-doc.mjs
 */
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve( dirname( fileURLToPath( import.meta.url ) ), '..' );
const output = resolve( root, '.github/coderabbit/wpds-tokens.md' );

const { tokens } = await import( '@wordpress/theme/design-tokens.js' );
const { version } = JSON.parse(
	readFileSync(
		resolve( root, 'node_modules/@wordpress/theme/package.json' ),
		'utf8'
	)
);

const groupTitles = {
	border: 'Border',
	color: 'Color',
	cursor: 'Cursor',
	dimension: 'Dimension',
	motion: 'Motion',
	typography: 'Typography',
};

const byGroup = {};
for ( const [ name, token ] of Object.entries( tokens ) ) {
	( byGroup[ token.group ] ??= [] ).push( [ name, token.$description ] );
}

const escapeCell = ( text ) => String( text ?? '' ).replace( /\|/g, '\\|' );

const sections = Object.keys( byGroup )
	.sort()
	.map( ( group ) => {
		const rows = byGroup[ group ]
			.map(
				( [ name, description ] ) =>
					`| \`${ name }\` | ${ escapeCell( description ) } |`
			)
			.join( '\n' );
		return `### ${
			groupTitles[ group ] ?? group
		}\n\n| Token | Use for |\n| ----- | ------- |\n${ rows }`;
	} )
	.join( '\n\n' );

const markdown = `<!-- Generated by bin/generate-wpds-tokens-doc.mjs from @wordpress/theme ${ version }. Do not edit by hand. -->

# WordPress Design System tokens

Review reference for styling in \`.css\`, \`.scss\`, and JS/TS style code. Use \`--wpds-*\` tokens instead of hardcoded values.

## Rules

- Don't hardcode colors, spacing, radii, font sizes, line heights, or transition durations and easings when a \`--wpds-*\` token exists for the role.
- Pick the token by semantic role (what is being styled), not by the nearest raw value.
- Don't invent token names. Only the tokens listed below exist.
- Keep the target and tone consistent across the background, foreground, and stroke of one element. Change only the state segment between states.
- Don't use legacy Sass palette variables or \`--wp-admin-*\` tokens in new code.

## Color naming

Color tokens follow \`--wpds-color-<property>-<target>-<tone>[-<emphasis>][-<state>]\`.

- Property: \`background\`, \`foreground\`, \`stroke\`.
- Target: \`surface\` (static containers), \`interactive\` (buttons, inputs, links), \`content\` (text and icons), \`track\`, \`thumb\`.
- Tone: \`neutral\`, \`brand\`, \`success\`, \`info\`, \`caution\`, \`warning\`, \`error\`. Use \`caution\` for minor risks and \`warning\` when the user must act.
- Emphasis: \`weak\`, \`strong\`. State: \`active\`, \`disabled\`.
- \`--wpds-color-stroke-focus\` is the only color token outside this grammar, used for focus rings.

## Tokens

${ sections }
`;

mkdirSync( dirname( output ), { recursive: true } );
writeFileSync( output, markdown );
console.log( `Wrote ${ output } (@wordpress/theme ${ version })` );
