/* eslint-disable @typescript-eslint/no-require-imports */

/**
 * External dependencies
 */
const fs = require( 'fs' );
const path = require( 'path' );
const {
	POSTCODE_REGEXES,
} = require( 'postcode-validator/lib/cjs/postcode-regexes.js' );
const { version } = require( 'postcode-validator/package.json' );
const { devDependencies } = require( '../package.json' );

const OUTPUT_PATH = path.resolve(
	__dirname,
	'../../../i18n/postcode-validation-rules.php'
);

// Stands in for each separator a format allows, so it can be typed or left out.
const OPTIONAL_SEPARATOR = '[ -]?';

// Where WooCommerce validates differently from the upstream package on purpose.
const COMPATIBILITY_OVERRIDES = {
	AT: '[0-9]{4}',
	BA: '[7-8][0-9]{4}',
	CA: '[ABCEGHJKLMNPRSTVXY][0-9][ABCEGHJKLMNPRSTVWXYZ] ?[0-9][ABCEGHJKLMNPRSTVWXYZ][0-9]',
	CZ: '(?:CZ-)?[0-9]{3}\\s?[0-9]{2}',
	DE: '(?:0[1-9]|[1-9][0-9])[0-9]{3}',
	DK: '(?:DK[- ]?)?(?:[1-24-9]\\d{3}|3[0-8]\\d{2})',
	ES: '[0-9]{5}',
	FI: '[0-9]{5}',
	FR: '[0-9]{5}',
	GB: '(?:[abcdefghijklmnoprstuwyz][abcdefghklmnopqrstuvwxy]?[0-9]{1,2} [0-9][abdefghjlnpqrstuwxyz]{2}|[abcdefghijklmnoprstuwyz][0-9][abcdefghjkpstuw] [0-9][abdefghjlnpqrstuwxyz]{2}|[abcdefghijklmnoprstuwyz][abcdefghklmnopqrstuvwxy][0-9][abehmnprvwxy] [0-9][abdefghjlnpqrstuwxyz]{2}|gir 0aa|bfpo [0-9]{1,4}|bfpo c\\/o [0-9]{1,3})',
	IE: '(?:[AC-FHKNPRTV-Y][0-9]{2}|D6W) [0-9AC-FHKNPRTV-Y]{4}',
	IN: '[1-9][0-9]{2}\\s?[0-9]{3}',
	JP: '[0-9]{3}-?[0-9]{4}',
	KH: '[0-9]{6}',
	LI: '94[8-9][0-9]',
	LV: '(?:LV[- ]?)?[1-9][0-9]{3}',
	MN: '[0-9]{5}(?:-[0-9]{4})?',
	NI: '[1-9][0-9]{4}',
	NL: '[1-9][0-9]{3}\\s?(?!SA|SD|SS)[A-Z]{2}',
	PR: '[0-9]{5}(?:-[0-9]{4})?',
	PT: '[0-9]{4}-[0-9]{3}',
	SE: '(?:SE-)?[0-9]{3}\\s?[0-9]{2}',
	SI: '[1-9][0-9]{3}',
	SK: '(?:SK-)?[0-9]{3}\\s?[0-9]{2}',
};

if ( devDependencies[ 'postcode-validator' ] !== version ) {
	throw new Error(
		`Installed postcode-validator ${ version } does not match the ${ devDependencies[ 'postcode-validator' ] } pin`
	);
}

/**
 * Remove the ECMAScript anchors supplied by postcode-validator. Consumers add
 * native anchors so PHP can use \A/\z while JavaScript uses ^/$.
 *
 * @param {RegExp} regex Upstream regular expression.
 * @return {string} Portable, unanchored expression source.
 */
function removeAnchors( regex ) {
	if ( ! regex.source.startsWith( '^' ) || ! regex.source.endsWith( '$' ) ) {
		throw new Error( `Expected an anchored expression: ${ regex.source }` );
	}

	return regex.source.slice( 1, -1 );
}

/**
 * Make every separator (space or hyphen) in a pattern optional, so a postcode
 * matches with or without it, but only where the format puts one. Hyphens
 * inside character classes (ranges) are kept.
 *
 * @param {string} pattern Regular expression source.
 * @return {string} Expression source with optional separators.
 */
function relaxSeparators( pattern ) {
	let out = '';

	for ( let i = 0; i < pattern.length; i++ ) {
		let token = pattern[ i ];
		let isSeparator = token === ' ' || token === '-';

		if ( token === '\\' ) {
			token += pattern[ i + 1 ];
			i++;
			isSeparator = token === '\\s' || token === '\\-';
		} else if ( token === '[' ) {
			const end = pattern.indexOf( ']', i + 1 );
			token = pattern.slice( i, end + 1 );
			i = end;
			// A class is a separator when it can only match separators.
			isSeparator = /^\[(?:[ -]|\\[s-])+\]$/.test( token );
		}

		if ( isSeparator ) {
			if ( pattern[ i + 1 ] === '?' ) {
				i++;
			}
			out += OPTIONAL_SEPARATOR;
		} else {
			out += token;
		}
	}

	return out;
}

/**
 * Quote a value for a PHP single quoted string.
 *
 * @param {string} value Value to quote.
 * @return {string} Quoted PHP literal.
 */
function toPhpString( value ) {
	return `'${ value.replaceAll( '\\', '\\\\' ).replaceAll( "'", "\\'" ) }'`;
}

// Strip INTL rule from the package.
const countryCodes = [ ...POSTCODE_REGEXES.keys() ]
	.filter( ( key ) => key !== 'INTL' )
	.sort();

const rules = Object.fromEntries(
	countryCodes.map( ( countryCode ) => {
		const upstreamRegex = POSTCODE_REGEXES.get( countryCode );

		const pattern = relaxSeparators(
			COMPATIBILITY_OVERRIDES[ countryCode ] ??
				removeAnchors( upstreamRegex )
		);

		// Catch malformed generated rules before they reach either consumer.
		new RegExp( `^(?:${ pattern })$`, 'i' );

		return [ countryCode, pattern ];
	} )
);

const unknownOverrides = Object.keys( COMPATIBILITY_OVERRIDES ).filter(
	( countryCode ) => ! rules[ countryCode ]
);
if ( unknownOverrides.length ) {
	throw new Error(
		`No postcode-validator rule to override for ${ unknownOverrides.join(
			', '
		) }`
	);
}

const phpEntries = countryCodes
	.map(
		( countryCode ) =>
			`\t'${ countryCode }' => ${ toPhpString( rules[ countryCode ] ) },`
	)
	.join( '\n' );

const php = `<?php
/**
 * Postcode validation rules.
 *
 * Generated from the postcode-validator npm package, version ${ version }
 * (https://www.npmjs.com/package/postcode-validator).
 *
 * Do not edit this file by hand. Run \`pnpm --filter @woocommerce/block-library generate:postcode-validation\`
 * to rebuild it. To change a rule on a store, use the \`woocommerce_postcode_validation_rules\` filter.
 *
 * @package WooCommerce\\i18n
 */

defined( 'ABSPATH' ) || exit;

return array(
${ phpEntries }
);
`;

fs.writeFileSync( OUTPUT_PATH, php );
